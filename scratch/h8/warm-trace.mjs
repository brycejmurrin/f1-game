import { chromium } from "playwright";
import { chromiumPath } from "../../tools/lib/chromium-path.mjs";
import { writeFileSync } from "node:fs";
const URL = process.argv[2] || "http://localhost:3456/";
const browser = await chromium.launch({ executablePath: chromiumPath(), args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true });
await ctx.addInitScript(() => { try { localStorage.setItem("apex26.devApi", "1"); } catch (_) {} });
const p1 = await ctx.newPage();
await p1.goto(URL, { waitUntil: "load" });
await p1.waitForFunction(() => window.__apex && __apex.info, null, { timeout: 120000 });
await p1.waitForTimeout(4000);
await p1.close();
const p2 = await ctx.newPage();
await browser.startTracing(p2, { path: "scratch/h8/warm-trace.json", categories: ["devtools.timeline", "disabled-by-default-devtools.timeline", "v8.execute", "blink.user_timing", "loading", "ServiceWorker"] });
await p2.goto(URL, { waitUntil: "load" });
await p2.waitForTimeout(1500);
await browser.stopTracing();
const r = await p2.evaluate(() => { const n = performance.getEntriesByType("navigation")[0]; const res = performance.getEntriesByType("resource"); return { ttfb: n.responseStart, dcl: n.domContentLoadedEventEnd, fcp: (performance.getEntriesByType("paint")[1] || {}).startTime, firstRes: Math.min(...res.map(e => e.startTime)), sw: !!navigator.serviceWorker.controller, workerStart: n.workerStart, fetchStart: n.fetchStart, reqStart: n.requestStart }; });
console.log(JSON.stringify(r));
await browser.close();
