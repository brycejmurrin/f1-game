#!/usr/bin/env node
/**
 * gen-coverage-table.mjs — docs/TESTING-COVERAGE.md from the test files on disk.
 * @doc Regenerates the per-file coverage page from each suite's header (or its groups.json note); `--check`.
 * @skill check-changes
 *
 * docs/TESTING.md §5 used to inline this table, so opening the how-to loaded
 * every suite's description. The how-to now links here. A row's text is the
 * note directly above the file in tests/groups.json `toolingFast` when one
 * exists, otherwise the first sentence of the file's header, otherwise the
 * first test title.
 *
 *   node tools/docs/gen-coverage-table.mjs
 *   node tools/docs/gen-coverage-table.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { argGate, emit, isMain, readRepo, ROOT } from "../gen/gen-lib.mjs";
import { headerSentence } from "../gen/gen-arch-table.mjs";

export const TARGET = "docs/TESTING-COVERAGE.md";
export const TARGETS = [TARGET];

const SUITES = [
  { dir: "tests/specs", title: "Playwright specs", re: /\.spec\.js$/ },
  { dir: "tests/unit", title: "Node unit suites", re: /\.test\.(mjs|cjs)$/ },
];

function toolingNotes() {
  const groups = JSON.parse(readRepo("tests/groups.json"));
  const notes = new Map();
  let buf = [];
  for (const line of groups.toolingFast || []) {
    if (typeof line === "string" && line.startsWith("//")) {
      buf.push(line.replace(/^\/\/\s?/, "").trim());
      continue;
    }
    if (buf.length && typeof line === "string") notes.set(line, buf.join(" "));
    buf = [];
  }
  return notes;
}

function firstTitle(src) {
  const m = src.match(/(?:^|\n)\s*(?:test|it)\(\s*(["'`])([^"'`]{8,200})\1/);
  return m ? m[2].replace(/\s+/g, " ").trim() : "";
}

export function describeFile(rel, src, notes) {
  const noted = notes.get(rel);
  const header = headerSentence(src);
  const title = firstTitle(src);
  let text = (noted || header || title || "—").replace(/\s+/g, " ").trim();
  if (text.length > 220) text = text.slice(0, 217).replace(/\s+\S*$/, "") + "…";
  return text.replace(/\|/g, "\\|");
}

export function suiteFiles() {
  const out = [];
  for (const suite of SUITES) {
    const names = fs.readdirSync(path.join(ROOT, suite.dir))
      .filter((name) => suite.re.test(name))
      .sort();
    out.push({ ...suite, names });
  }
  return out;
}

export function renderCoverage() {
  const notes = toolingNotes();
  const lines = [
    "# Test coverage",
    "",
    "_Generated by `node tools/docs/gen-coverage-table.mjs` from the test files on disk. Do not hand-edit. `docs/TESTING.md` §5 links here; `--check` fails when this page drifts._",
    "",
  ];
  for (const suite of suiteFiles()) {
    lines.push(`## ${suite.title}`, "", "| Test | What it covers |", "|---|---|");
    for (const name of suite.names) {
      const rel = `${suite.dir}/${name}`;
      lines.push(`| \`${name}\` | ${describeFile(rel, readRepo(rel), notes)} |`);
    }
    lines.push("");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

function main() {
  const argv = process.argv.slice(2);
  const gated = argGate(argv, { tool: "tools/docs/gen-coverage-table.mjs" });
  if (gated !== null) return gated;
  const check = argv.includes("--check") ? ["--check"] : [];
  return emit(TARGET, renderCoverage(), check);
}

if (isMain(import.meta.url)) process.exit(main());
