#!/usr/bin/env node
/**
 * gen-coverage-table.mjs — artifacts/TESTING-COVERAGE.md from the test files on disk.
 * @doc Builds the per-file coverage page (artifacts/, never committed) from each suite's header or groups.json note.
 * @skill check-changes
 *
 * docs/TESTING.md §5 used to inline this table, so opening the how-to loaded
 * every suite's description. The how-to now links here. A row's text is the
 * first sentence of the file's own header; a file with no header takes the
 * note directly above it in tests/groups.json `toolingFast`, unless that note
 * is a continuation ("...and the"); otherwise the first test title.
 *
 * Header first, because the file is the only text that is always about itself:
 * `toolingFast` is kept sorted, and a sort moves a file away from the comment
 * written for it while the comment stays put — the ready-gate.test.mjs row
 * described a real-race replay test, and 15 rows opened "...and the" (audit W27,
 * 2026-11-09). A note that reads as a continuation of the line above is never
 * attached to the file below it.
 *
 * BUILT ON DEMAND, NOT COMMITTED (2026-11-10, the #5349 pattern). The page used
 * to be committed as docs/TESTING-COVERAGE.md. Every PR that adds or renames a
 * test rewrites a row of it, so each merge to the deploy branch left the other
 * open PRs CONFLICTING in it: 16 open PRs carried it on 2026-11-10 and 15 of them
 * conflicted with the tip, 9 on nothing else. Each conflict cost a sync push and
 * a full CI run. It is now written to artifacts/ (gitignored), and the old path
 * is RETIRED_PATHS in tools/lib/generated-paths.mjs: an old branch's modify/delete
 * conflict cures by taking the deletion (deploy.mjs cureableConflicts).
 * tests/unit/test-groups.test.mjs keeps the real guard: every suite has a row.
 *
 *   node tools/docs/gen-coverage-table.mjs           # writes artifacts/TESTING-COVERAGE.md
 *   node tools/docs/gen-coverage-table.mjs --check   # renders it, writes nothing: there is no committed copy to
 *                                                    # drift, and `gen:check` keeps the flag so package.json is
 *                                                    # untouched (12 open PRs edit it; a script edit conflicts)
 */
import fs from "node:fs";
import path from "node:path";
import { argGate, emit, isMain, readRepo, ROOT } from "../gen/gen-lib.mjs";
import { headerSentence } from "../gen/gen-arch-table.mjs";

export const TARGET = "artifacts/TESTING-COVERAGE.md";

const SUITES = [
  { dir: "tests/specs", title: "Playwright specs", re: /\.spec\.js$/ },
  { dir: "tests/unit", title: "Node unit suites", re: /\.test\.(mjs|cjs)$/ },
];

function toolingNotes() {
  const groups = JSON.parse(readRepo("tests/groups.json"));
  const notes = new Map();
  let buf = [];
  for (const line of groups.toolingFast || []) {
    if (typeof line === "string" && line.startsWith("//")) {
      buf.push(line.replace(/^\/\/\s?/, "").trim());
      continue;
    }
    if (buf.length && typeof line === "string") notes.set(line, buf.join(" "));
    buf = [];
  }
  return notes;
}

function firstTitle(src) {
  const m = src.match(/(?:^|\n)\s*(?:test|it)\(\s*(["'`])([^"'`]{8,200})\1/);
  return m ? m[2].replace(/\s+/g, " ").trim() : "";
}

export const isContinuation = (note) => /^(?:\.\.\.|…|and\b|or\b|plus\b|then\b|also\b)/i.test(note || "");

export function describeFile(rel, src, notes) {
  const raw = notes.get(rel);
  const noted = raw && !isContinuation(raw) ? raw : null;
  const header = headerSentence(src);
  const title = firstTitle(src);
  let text = (header || noted || title || "—").replace(/\s+/g, " ").trim();
  if (text.length > 220) text = text.slice(0, 217).replace(/\s+\S*$/, "") + "…";
  return text.replace(/\|/g, "\\|");
}

export function suiteFiles() {
  const out = [];
  for (const suite of SUITES) {
    const names = fs.readdirSync(path.join(ROOT, suite.dir))
      .filter((name) => suite.re.test(name))
      .sort();
    out.push({ ...suite, names });
  }
  return out;
}

export function renderCoverage() {
  const notes = toolingNotes();
  const lines = [
    "# Test coverage",
    "",
    "_Generated by `node tools/docs/gen-coverage-table.mjs` from the test files on disk. Built on demand, never committed: `docs/TESTING.md` §5 says how to open it._",
    "",
  ];
  for (const suite of suiteFiles()) {
    lines.push(`## ${suite.title}`, "", "| Test | What it covers |", "|---|---|");
    for (const name of suite.names) {
      const rel = `${suite.dir}/${name}`;
      lines.push(`| \`${name}\` | ${describeFile(rel, readRepo(rel), notes)} |`);
    }
    lines.push("");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

function main() {
  const argv = process.argv.slice(2);
  const gated = argGate(argv, { tool: "tools/docs/gen-coverage-table.mjs" });
  if (gated !== null) return gated;
  const page = renderCoverage();
  if (argv.includes("--check")) {
    process.stdout.write(`${TARGET}: renders (${Buffer.byteLength(page, "utf8")} bytes); built on demand, nothing committed to check\n`);
    return 0;
  }
  fs.mkdirSync(path.join(ROOT, path.dirname(TARGET)), { recursive: true });
  return emit(TARGET, page, []);
}

if (isMain(import.meta.url)) process.exit(main());
