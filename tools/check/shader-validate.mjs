#!/usr/bin/env node
// @doc glslang over the GLX GLSL ES 3.00 shaders, naga (advisory) over the WGX WGSL; offline, skips LOUDLY without the binary.
// @skill renderer-debug
//
// WHY. A shader typo reaches a browser only through a 10-40 min SwiftShader group, or a player whose
// driver says "compile failed" and silently drops to another backend. The reference compilers find
// the same error in seconds, with no GPU.
//
//   node tools/check/shader-validate.mjs               # the tree
//   node tools/check/shader-validate.mjs --require     # absent glslang = failure (CI: APEX_REQUIRE_LINT_BINS=1)
//   node tools/check/shader-validate.mjs --strict-naga # naga findings fail too (default: advisory)
//   node tools/check/shader-validate.mjs --json
//
// WHAT IS CHECKED
//   GLX   js/render/glx/shaders/glsl-*.js (every program in GLXShaders, evaluated in a vm so the
//         ${GLXChunks.*} interpolations are real) plus the static *_VS/*_FS string constants in
//         glx.js / post.js / chunked.js. Stage from the name suffix. A source that tests a
//         #ifdef GLX_PERSP_SCALAR gets BOTH variants (post.js injects the define at runtime).
//         Validator: glslangValidator (Khronos reference; ES 3.00 accepts what ANGLE accepts, but a
//         driver can still reject what glslang allows - this finds errors, it does not prove a GPU).
//   WGX   js/render/webgpu/wgsl-*.js entry-point modules (vm-evaluated WGSLChunks/Post/Fx).
//         Validator: naga. ADVISORY: Chrome's compiler is Tint, and naga disagrees with it in places,
//         so a naga rejection is a WARN row (named, with naga's message) unless --strict-naga, and a
//         missing naga fails --require only with --strict-naga. On the tree today naga accepts every
//         module, so no dialect gap is recorded. Authoritative WGSL validation remains `node tools/gfx/wgx-validate.mjs` (real Dawn, parent session).
//   TLX   NOT CHECKED, by design: js/render/three/ builds its materials from TSL node graphs, so the
//         GLSL/WGSL is generated by three.js at runtime from a live renderer. There is no complete
//         shader stage in the source to extract (no ShaderMaterial / onBeforeCompile anywhere in js/).
//   SKIPPED (named, not hidden): WGSLPost.POST_VS is a vertex snippet interpolated into every post
//         pass, not a module; it is validated as part of each pass that embeds it.
//
// Binaries: tools/env/install-lint-bins.sh. No network at run time. Output files go to
// artifacts/shader-validate/. Exit 0 clean (or SKIPPED), 1 findings, 2 tool error.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { pathToFileURL } from "node:url";
import * as espree from "espree";
import { ROOT, requireBins, resolveBin, skipLine, versionOf } from "../lib/lint-bins.mjs";

const OUT = path.join(ROOT, "artifacts/shader-validate");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");

/** WGSL snippets that are interpolated into other modules rather than compiled alone. */
export const WGSL_FRAGMENTS = Object.freeze({ "WGSLPost.POST_VS": "vertex snippet embedded in every post pass module" });

const stageOf = (name) => (/_VS$/.test(name) ? "vert" : "frag");

/** Evaluate a static string expression (literals, no-expression templates, `+`); null if dynamic. */
function staticString(node) {
  if (!node) return null;
  if (node.type === "Literal") return typeof node.value === "string" ? node.value : null;
  if (node.type === "TemplateLiteral" && node.expressions.length === 0) return node.quasis.map((q) => q.value.cooked).join("");
  if (node.type === "BinaryExpression" && node.operator === "+") {
    const l = staticString(node.left), r = staticString(node.right);
    return l !== null && r !== null ? l + r : null;
  }
  return null;
}

function inlineGlsl(rel) {
  const found = [];
  const walk = (n) => {
    if (!n || typeof n !== "object") return;
    if (Array.isArray(n)) return n.forEach(walk);
    if (n.type === "VariableDeclarator" && n.id?.type === "Identifier" && /_(VS|FS)$/.test(n.id.name)) {
      const src = staticString(n.init);
      if (src && src.startsWith("#version 300 es")) found.push({ id: `${path.basename(rel)}:${n.id.name}`, stage: stageOf(n.id.name), source: src });
    }
    for (const k of Object.keys(n)) if (k !== "loc" && k !== "range") walk(n[k]);
  };
  walk(espree.parse(read(rel), { ecmaVersion: "latest", sourceType: "script" }));
  return found;
}

/** Every GLSL ES 3.00 program the GLX backend compiles: [{id, stage, source}]. */
export function extractGlsl() {
  const ctx = vm.createContext({});
  ctx.window = ctx;
  for (const f of ["glsl-chunks", "glsl-sky", "glsl-fx", "glsl-lit", "glsl-post"]) {
    vm.runInContext(read(`js/render/glx/shaders/${f}.js`), ctx, { filename: f });
  }
  const out = [];
  for (const [name, source] of Object.entries(ctx.GLXShaders || {})) {
    if (typeof source !== "string") continue;
    out.push({ id: name, stage: stageOf(name), source });
    if (source.includes("GLX_PERSP_SCALAR")) {
      out.push({ id: `${name}+GLX_PERSP_SCALAR`, stage: stageOf(name), source: source.replace("#version 300 es\n", "#version 300 es\n#define GLX_PERSP_SCALAR 1\n") });
    }
  }
  for (const rel of ["js/render/glx/glx.js", "js/render/glx/post.js", "js/render/glx/chunked.js"]) out.push(...inlineGlsl(rel));
  return out;
}

/** Every complete WGSL module (has an entry point): [{id, source}]. */
export function extractWgsl() {
  const ctx = vm.createContext({});
  ctx.window = ctx;
  for (const f of ["wgsl-chunks", "wgsl-post", "wgsl-fx"]) vm.runInContext(read(`js/render/webgpu/${f}.js`), ctx, { filename: f });
  const out = [];
  for (const ns of ["WGSLChunks", "WGSLPost", "WGSLFx"]) {
    for (const [k, v] of Object.entries(ctx[ns] || {})) {
      if (typeof v !== "string" || !/@(vertex|fragment|compute)\b/.test(v)) continue;
      if (WGSL_FRAGMENTS[`${ns}.${k}`]) continue;
      out.push({ id: `${ns}.${k}`, source: v });
    }
  }
  return out;
}

const safe = (id) => id.replace(/[^A-Za-z0-9_.+-]/g, "_");
function write(name, source) {
  fs.mkdirSync(OUT, { recursive: true });
  const p = path.join(OUT, name);
  fs.writeFileSync(p, source);
  return p;
}

/** @returns {{ok: boolean, output: string}} */
export function validateGlsl(bin, { id, stage, source }) {
  const r = spawnSync(bin, ["-S", stage, write(`${safe(id)}.${stage}`, source)], { encoding: "utf8" });
  const output = `${r.stdout}${r.stderr}`.trim();
  return { ok: r.status === 0 && !/^ERROR:/m.test(output), output };
}

/** @returns {{ok: boolean, output: string}} */
export function validateWgsl(bin, { id, source }) {
  const r = spawnSync(bin, [write(`${safe(id)}.wgsl`, source)], { encoding: "utf8" });
  return { ok: r.status === 0, output: `${r.stdout}${r.stderr}`.trim() };
}

/** Validate the whole tree. rows: {kind, id, status: "ok"|"fail"|"warn", output}. */
export function validateTree({ strictNaga = false } = {}) {
  const rows = [], tools = {};
  const glslang = resolveBin("glslangValidator"), naga = resolveBin("naga");
  if (!glslang) rows.push({ kind: "glsl", id: "*", status: "skipped", output: skipLine("shader-validate", "glslangValidator") });
  else {
    tools.glslangValidator = versionOf(glslang);
    for (const s of extractGlsl()) {
      const r = validateGlsl(glslang, s);
      rows.push({ kind: "glsl", id: s.id, status: r.ok ? "ok" : "fail", output: r.ok ? "" : r.output });
    }
  }
  if (!naga) rows.push({ kind: "wgsl", id: "*", status: "skipped", advisory: !strictNaga, output: skipLine("shader-validate", "naga") });
  else {
    tools.naga = versionOf(naga);
    for (const s of extractWgsl()) {
      const r = validateWgsl(naga, s);
      rows.push({ kind: "wgsl", id: s.id, status: r.ok ? "ok" : strictNaga ? "fail" : "warn", output: r.ok ? "" : r.output });
    }
  }
  return { rows, tools };
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  const argv = process.argv.slice(2);
  const { rows, tools } = validateTree({ strictNaga: argv.includes("--strict-naga") });
  if (argv.includes("--json")) console.log(JSON.stringify({ tools, rows }, null, 2));
  const count = (k, s) => rows.filter((r) => r.kind === k && r.status === s).length;
  for (const r of rows) {
    if (r.status === "skipped") console.error(r.output);
    else if (r.status !== "ok") console.error(`${r.status.toUpperCase()} ${r.kind} ${r.id}\n${r.output}`);
  }
  if (!argv.includes("--json")) {
    console.log(`shader-validate: ${Object.entries(tools).map(([k, v]) => `${k} ${v}`).join("; ") || "no tools"}`);
    for (const k of ["glsl", "wgsl"]) console.log(`  ${k}: ${count(k, "ok")} ok, ${count(k, "fail")} fail, ${count(k, "warn")} warn (advisory), ${count(k, "skipped")} skipped`);
    console.log("  tlx: not checked (TSL node graphs; no static shader stage) - see the header of this file");
  }
  const fail = rows.some((r) => r.status === "fail");
  const skipped = rows.some((r) => r.status === "skipped" && !r.advisory);
  process.exit(fail || (skipped && requireBins(argv)) ? 1 : 0);
}
