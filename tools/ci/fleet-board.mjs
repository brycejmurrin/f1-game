#!/usr/bin/env node
// fleet-board.mjs — the backlog's phone view and the claim mirror, run hourly by .github/workflows/fleet.yml.
// @doc Fleet board: current/stale claims, PR associations and backlog labels on one pinned issue.
// Full description: Reads open issues/PRs, GitHub issue cross-references and closing links, and the claims board. Shows ownership separately from PR association (including merged partial work); derives claimed from current claims or open PRs with closing intent or an issue number explicitly in their title. Other references are displayed without claiming ownership. Syncs labels and the existing pinned board only with --apply. Incomplete API/claim evidence aborts before writes.
// @skill steward
//
// docs/notes/AGENT-WORK-TRACKING-2026-10-14.md: the backlog is GitHub issues
// (AGENTS.md §Backlog) and Bryce reads the fleet from a phone, where a filtered
// issue list is three taps and a PR list another three. This puts the whole
// state on one pinned issue. It also closes the two gaps the convention left
// to discipline: an agent that claims `#<n>` through who-is-on-it.mjs but
// forgets the label, and a PR closed unmerged that leaves its issue `claimed`
// for ever. The label is DERIVED here from current claims and explicitly issue-scoped open PRs. Stale claims remain visible
// without asserting ownership; merged references never prove completion.
//
// Runs in Actions, not in agent containers: the containers' proxy refuses
// most of the REST API (who-is-on-it.mjs records the 403s), the Actions token
// does not. Events made with that token start no further workflow runs
// (docs.github.com, "Triggering a workflow from a workflow"), so the board's
// own edits cannot loop.
//
//   node tools/ci/fleet-board.mjs                 # print the board and the label plan
//   node tools/ci/fleet-board.mjs --apply         # write labels, comments and the board (needs GH_TOKEN)

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseBoard, readBoard, CLAIMS_BOARD, BOARD_MAX_MIN, STALE_MIN } from "./who-is-on-it.mjs";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
export const BOARD_MARKER = "<!-- fleet-board: generated by tools/ci/fleet-board.mjs; edits are overwritten -->";
const BOARD_TITLE = "Fleet board";

/** Issue numbers a claim's text names: `#123`, never `PR#` fragments of words. */
export const refsIn = (text) => [...String(text).matchAll(/(?:^|[^\w&])#(\d+)\b/g)].map((m) => Number(m[1]));

/** Issue numbers a PR body closes, by GitHub's closing keywords. */
export const closesIn = (body) =>
  [...String(body || "").matchAll(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s*:?\s+#(\d+)\b/gi)].map((m) => Number(m[1]));

const names = (issue) => (issue.labels || []).map((l) => (typeof l === "string" ? l : l.name));

/** Who holds each issue. Pure. claims: parseBoard rows; prs: {number, body, draft}. */
export function holders(claims, prs, maxAgeMin = STALE_MIN, coverage = new Map()) {
  const by = new Map();
  for (const c of claims) {
    if (c.released || c.ageMin > maxAgeMin) continue;
    for (const n of refsIn(c.text)) if (!by.has(n)) by.set(n, { kind: "claim", who: c.who, text: c.text });
  }
  for (const p of prs) for (const n of closesIn(p.body)) by.set(n, { kind: "pr", pr: p.number, draft: !!p.draft });
  for (const [n, links] of coverage) {
    const open = links.find((p) => p.state === "OPEN" && (p.closing || p.scoped));
    if (open && !by.has(n)) by.set(n, { kind: "pr", pr: open.number, draft: open.isDraft, referenceOnly: !open.closing });
  }
  return by;
}

/** The label writes that make `claimed` true. Pure.
 *  Returns [{number, add: [...], remove: [...], comment?}]. */
export function labelPlan(issues, held) {
  const plan = [];
  for (const i of issues) {
    const has = new Set(names(i));
    const h = held.get(i.number);
    if (h && !has.has("claimed")) {
      const by = h.kind === "pr" ? `PR #${h.pr}${h.referenceOnly ? " (association; scope unverified)" : ""}` : `${h.who || "a session"}: ${h.text}`;
      plan.push({ number: i.number, add: ["claimed"], remove: [], comment: `Claimed — ${by}` });
    } else if (!h && has.has("claimed")) {
      plan.push({ number: i.number, add: [], remove: ["claimed"],
        comment: "Released — no current claim or explicitly issue-scoped open PR was found. Context references and stale claims do not establish ownership, readiness or completion; review PR scope and remaining acceptance criteria before pickup." });
    }
  }
  return plan;
}

const ago = (iso, now) => {
  const h = Math.round((now - Date.parse(iso)) / 3600000);
  return h < 1 ? "<1 h" : h < 48 ? `${h} h` : `${Math.round(h / 24)} d`;
};

/** The board issue's body. Pure. */
export function renderBoard({ issues, prs, claims, held, coverage = new Map(), now = Date.now() }) {
  const line = (i) => `- #${i.number} ${i.title}`;
  const ready = issues.filter((i) => names(i).includes("ready") && !held.has(i.number) && !names(i).includes("blocked"));
  const claimed = issues.filter((i) => held.has(i.number));
  const blocked = issues.filter((i) => names(i).includes("blocked") && !held.has(i.number));
  const live = claims.filter((c) => !c.released && c.ageMin <= STALE_MIN);
  const out = [BOARD_MARKER, "",
    `Updated ${new Date(now).toISOString().slice(0, 16).replace("T", " ")} UTC · ready ${ready.length} · claimed ${claimed.length} · blocked ${blocked.length} · open PRs ${prs.length} · live claims ${live.length}`,
    "", "Pick up work: `list_issues` with `labels: [\"ready\"]`, skipping `claimed` / `blocked` (AGENTS.md §Backlog).",
    "", `## Ready (${ready.length})`, ...(ready.length ? ready.map(line) : ["_(empty)_"]),
    "", `## Claimed (${claimed.length})`, ...(claimed.length ? claimed.map((i) => {
      const h = held.get(i.number);
      return `${line(i)} — ${h.kind === "pr" ? `PR #${h.pr}${h.draft ? " (draft)" : ""}${h.referenceOnly ? " (association; scope unverified)" : ""}` : `claim: ${h.who || "?"}`}`;
    }) : ["_(none)_"]),
    "", `## Blocked (${blocked.length})`, ...(blocked.length ? blocked.map(line) : ["_(none)_"]),
    "", "## Issue coverage and ownership",
    "PR links are associations, not proof of completion. Closing intent is shown separately; merged references may be partial. Close only against the issue acceptance evidence. Stale claims are unverified ownership, not a lock.", "",
    "| Issue | Current claim | PR associations | Stale claim |",
    "|---|---|---|---|",
    ...issues.map((i) => {
      const current = live.filter((c) => refsIn(c.text).includes(i.number));
      const stale = claims.filter((c) => !c.released && c.ageMin > STALE_MIN && c.ageMin <= BOARD_MAX_MIN && refsIn(c.text).includes(i.number));
      const links = coverage.get(i.number) || [];
      const cell = (text) => String(text).replace(/[|\r\n]/g, " ");
      return `| #${i.number} ${cell(i.title)} | ${current.map((c) => cell(c.who)).join(", ") || "none"} | ${links.map((p) => `#${p.number} ${p.state.toLowerCase()}${p.isDraft ? " draft" : ""} (${p.closing ? "closing intent" : "reference; scope unverified"})`).join("; ") || "none found"} | ${stale.map((c) => `${cell(c.who)} ${Math.round(c.ageMin / 60)} h`).join(", ") || "none"} |`;
    }),
    "", `## Open PRs (${prs.length})`, ...(prs.length ? prs.map((p) =>
      `- #${p.number} ${p.draft ? "📝 " : ""}${p.title} — ${ago(p.updated_at, now)} ago${closesIn(p.body).length ? ` · closes ${closesIn(p.body).map((n) => "#" + n).join(", ")}` : ""}`) : ["_(none)_"]),
    "", `## Live claims (${live.length})`, ...(live.length ? live.map((c) => `- ${Math.round(c.ageMin / 6) / 10} h — ${c.who}: ${c.text}`) : ["_(none)_"]),
    ""];
  return out.join("\n");
}

/** Normalize same-repository GitHub timeline links; never infer completion from a reference. */
export function coverageOf(nodes, repo) {
  const by = new Map();
  for (const issue of nodes) {
    if (issue.timelineItems.pageInfo.hasNextPage) throw new Error(`issue #${issue.number}: incomplete cross-reference timeline; refusing writes`);
    const links = new Map();
    for (const event of issue.timelineItems.nodes) {
      const p = event.source;
      if (!p?.number || p.repository?.nameWithOwner !== repo) continue;
      const prior = links.get(p.number);
      links.set(p.number, { number: p.number, state: p.state, isDraft: p.isDraft, closing: !!event.willCloseTarget || !!prior?.closing, scoped: refsIn(p.title).includes(issue.number) });
    }
    by.set(issue.number, [...links.values()].sort((a, b) => b.number - a.number));
  }
  return by;
}

const sleepSync = (ms) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

/** Run a READ-ONLY `gh` call, retrying only a transient gateway error (HTTP 502/503/504) after each delay; any other error throws at once. */
export function ghRetry(args, { run = (a) => gh(a), delays = [2000, 5000], sleep = sleepSync } = {}) {
  for (let attempt = 0; ; attempt++) {
    try { return run(args); } catch (e) {
      if (attempt >= delays.length || !/HTTP 50[234]/.test(`${e?.message || ""}\n${e?.stderr || ""}`)) throw e;
      sleep(delays[attempt]);
    }
  }
}

/** Paginated GraphQL issue timelines and canonical open-PR closing links. Fail closed on incomplete data.
 *  A transient HTTP 502/503/504 is retried twice (ghRetry); every other error, and a third gateway error, still aborts. */
export function readCoverage(repo, request = (query, variables) => JSON.parse(ghRetry(["api", "graphql", "-f", `query=${query}`, ...Object.entries(variables).flatMap(([k, v]) => ["-f", `${k}=${v}`])])).data) {
  const [owner, name] = repo.split("/");
  const query = `query($owner:String!,$name:String!,$cursor:String){repository(owner:$owner,name:$name){issues(first:25,after:$cursor,states:OPEN){nodes{number timelineItems(first:100,itemTypes:[CROSS_REFERENCED_EVENT]){nodes{... on CrossReferencedEvent{willCloseTarget source{... on PullRequest{number title state isDraft repository{nameWithOwner}}}}}pageInfo{hasNextPage}}}pageInfo{hasNextPage endCursor}}}}`;
  const nodes = [];
  let cursor;
  do {
    const data = request(query, { owner, name, ...(cursor ? { cursor } : {}) });
    const page = data.repository.issues;
    nodes.push(...page.nodes);
    cursor = page.pageInfo.hasNextPage ? page.pageInfo.endCursor : null;
    if (page.pageInfo.hasNextPage && !cursor) throw new Error("incomplete issue pagination");
  } while (cursor);
  const coverage = coverageOf(nodes, repo);
  const prQuery = `query($owner:String!,$name:String!,$cursor:String){repository(owner:$owner,name:$name){pullRequests(first:100,after:$cursor,states:OPEN){nodes{number title isDraft closingIssuesReferences(first:100){nodes{number repository{nameWithOwner}}pageInfo{hasNextPage}}}pageInfo{hasNextPage endCursor}}}}`;
  do {
    const page = request(prQuery, { owner, name, ...(cursor ? { cursor } : {}) }).repository.pullRequests;
    for (const p of page.nodes) {
      if (p.closingIssuesReferences.pageInfo.hasNextPage) throw new Error(`PR #${p.number}: incomplete closing links; refusing writes`);
      for (const i of p.closingIssuesReferences.nodes) {
        if (i.repository.nameWithOwner !== repo || !coverage.has(i.number)) continue;
        const links = coverage.get(i.number);
        const prior = links.find((x) => x.number === p.number);
        if (prior) Object.assign(prior, { state: "OPEN", isDraft: p.isDraft, closing: true, scoped: refsIn(p.title).includes(i.number) });
        else links.unshift({ number: p.number, state: "OPEN", isDraft: p.isDraft, closing: true, scoped: refsIn(p.title).includes(i.number) });
      }
    }
    cursor = page.pageInfo.hasNextPage ? page.pageInfo.endCursor : null;
    if (page.pageInfo.hasNextPage && !cursor) throw new Error("incomplete PR pagination");
  } while (cursor);
  return coverage;
}

/** .github/labels.json, validated. */
export function readLabels(root = ROOT) {
  const list = JSON.parse(fs.readFileSync(path.join(root, ".github/labels.json"), "utf8"));
  for (const l of list) {
    if (!/^[0-9a-f]{6}$/i.test(l.color || "")) throw new Error(`label ${l.name}: color must be 6 hex digits`);
    if (typeof l.name !== "string" || !l.name || typeof l.description !== "string" || !l.description)
      throw new Error(`label ${JSON.stringify(l)}: name and description must be non-empty strings`);
    for (const [field, max] of [["name", 50], ["description", 100]]) {
      const length = Array.from(l[field]).length;
      if (length > max) throw new Error(`label ${JSON.stringify(l.name)}: ${field} must be ${max} characters or fewer (got ${length})`);
    }
  }
  return list;
}

const gh = (args, input) => execFileSync("gh", args, { encoding: "utf8", input, maxBuffer: 64 << 20 });
const ghJson = (args) => gh(["api", "--paginate", ...args, "--jq", "tojson"]).trim().split("\n").filter(Boolean).flatMap((line) => JSON.parse(line));

export function main(argv = process.argv.slice(2)) {
  const apply = argv.includes("--apply");
  const repo = process.env.GITHUB_REPOSITORY || "brycejmurrin/f1-game";
  const all = ghJson([`repos/${repo}/issues?state=open&per_page=100`]);
  const boardIssue = all.find((i) => !i.pull_request && String(i.body || "").startsWith(BOARD_MARKER));
  const issues = all.filter((i) => !i.pull_request && i !== boardIssue);
  const prs = ghJson([`repos/${repo}/pulls?state=open&per_page=100`]);
  // A missing/unread claim ref must never release other sessions' ownership.
  gh(["api", `repos/${repo}`]); // establish API access before any write
  execFileSync("git", ["fetch", "origin", `${CLAIMS_BOARD}:refs/remotes/origin/${CLAIMS_BOARD}`], { cwd: ROOT, stdio: "pipe" });
  execFileSync("git", ["cat-file", "-e", `refs/remotes/origin/${CLAIMS_BOARD}^{commit}`], { cwd: ROOT });
  const coverage = readCoverage(repo);
  for (const i of issues) if (!coverage.has(i.number)) throw new Error(`issue #${i.number} missing from coverage snapshot; retry before applying`);
  const claims = parseBoard(readBoard(`refs/remotes/origin/${CLAIMS_BOARD}`));
  const held = holders(claims, [], STALE_MIN, coverage);
  const plan = labelPlan(issues, held);
  const body = renderBoard({ issues, prs, claims, held, coverage });

  console.log(`# ${issues.length} open issues, ${prs.length} open PRs, ${claims.length} board claims; ${plan.length} label change(s)`);
  for (const p of plan) console.log(`  #${p.number} +[${p.add}] -[${p.remove}] ${p.comment}`);
  if (!apply) { console.log("\n" + body); return 0; }

  for (const l of readLabels()) gh(["label", "create", l.name, "--repo", repo, "--color", l.color, "--description", l.description, "--force"]);
  for (const p of plan) {
    for (const a of p.add) gh(["issue", "edit", String(p.number), "--repo", repo, "--add-label", a]);
    for (const r of p.remove) gh(["issue", "edit", String(p.number), "--repo", repo, "--remove-label", r]);
    if (p.comment) gh(["issue", "comment", String(p.number), "--repo", repo, "--body-file", "-"], p.comment);
  }
  let n = boardIssue?.number;
  if (n) gh(["issue", "edit", String(n), "--repo", repo, "--body-file", "-"], body);
  else {
    const url = gh(["issue", "create", "--repo", repo, "--title", BOARD_TITLE, "--label", "fleet-board", "--body-file", "-"], body).trim();
    n = Number(url.split("/").pop());
  }
  // Pinning is idempotent in intent; gh errors when it is already pinned.
  try { gh(["issue", "pin", String(n), "--repo", repo]); } catch (e) { console.log(`pin #${n}: ${String(e.message).split("\n")[0]}`); }
  console.log(`# board → #${n}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main());
