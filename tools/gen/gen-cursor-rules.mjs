#!/usr/bin/env node
/**
 * gen-cursor-rules.mjs — emit `.cursor/rules/*.mdc` from `.claude/rules/*.md`.
 * @doc Emit `.cursor/rules/*.mdc` from `.claude/rules` (`paths`→`globs`, else `alwaysApply`); `--check`.
 * @skill agent-config
 *
 * `.claude/rules/<name>.md` is the source. Cursor reads `.cursor/rules/<name>.mdc`
 * with different frontmatter (`globs` / `alwaysApply`). Hand-mirroring drifted
 * (stale paths lived for weeks); this generator owns the `.mdc` copies.
 * `apex-shared.mdc` stays hand-written (Cursor-only).
 *
 *   node tools/gen/gen-cursor-rules.mjs            # write every twin
 *   node tools/gen/gen-cursor-rules.mjs --check    # exit 1 on any drift
 */
import fs from "node:fs";
import path from "node:path";
import { argGate, firstDiff, isMain, ROOT } from "./gen-lib.mjs";

export const SRC_DIR = ".claude/rules";
export const OUT_DIR = ".cursor/rules";
/** Hand-written Cursor-only entry — never overwritten. */
export const HAND_WRITTEN = new Set(["apex-shared.mdc"]);

const stripFrontmatter = (text) => {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  return { fm: m ? m[1] : "", body: m ? text.slice(m[0].length) : text };
};

/** Parse a minimal YAML `paths:` list of quoted strings. */
export function parsePaths(fm) {
  const paths = [];
  let inPaths = false;
  for (const raw of String(fm || "").split("\n")) {
    const line = raw.replace(/\s+#.*$/, "");
    if (/^paths:\s*$/.test(line)) { inPaths = true; continue; }
    if (inPaths) {
      const item = line.match(/^\s*-\s*"([^"]+)"\s*$/);
      if (item) { paths.push(item[1]); continue; }
      if (/^\S/.test(line) && line.trim()) break;
    }
  }
  return paths;
}

/** First `# …` heading line in the body → Cursor `description:` (≤ 120 chars). */
export function descriptionFromBody(body, fallback) {
  const m = String(body || "").match(/^#\s+(.+)$/m);
  const raw = (m ? m[1] : fallback).replace(/\s+/g, " ").trim();
  return raw.length <= 120 ? raw : raw.slice(0, 117) + "...";
}

/**
 * Build one `.mdc` file from a Claude rule source.
 * No `paths:` → alwaysApply: true. Else globs: comma-joined (Cursor form).
 */
export function renderMdc(name, srcText) {
  const { fm, body } = stripFrontmatter(srcText);
  const paths = parsePaths(fm);
  const desc = descriptionFromBody(body, name);
  const header = [
    "---",
    `description: ${desc}`,
    paths.length
      ? `globs: ${paths.join(",")}`
      : "alwaysApply: true",
    ...(paths.length ? ["alwaysApply: false"] : []),
    "---",
    "",
    `<!-- generated by tools/gen/gen-cursor-rules.mjs — edit .claude/rules/${name}.md -->`,
    "",
  ].join("\n");
  const bodyOut = body.replace(/^\n+/, "").replace(/\s+$/, "") + "\n";
  return header + bodyOut;
}

export function listRuleSources() {
  const dir = path.join(ROOT, SRC_DIR);
  return fs.readdirSync(dir)
    .filter((n) => n.endsWith(".md"))
    .map((n) => n.replace(/\.md$/, ""))
    .sort();
}

/** @returns {{ name: string, rel: string, content: string }[]} */
export function plannedOutputs() {
  return listRuleSources().map((name) => {
    const src = fs.readFileSync(path.join(ROOT, SRC_DIR, `${name}.md`), "utf8");
    return { name, rel: `${OUT_DIR}/${name}.mdc`, content: renderMdc(name, src) };
  });
}

/**
 * Write or check every twin. Exit: 0 clean, 1 drift, 2 bad argv.
 * Also refuses a hand-written file that shares a source name, and flags
 * orphan generated `.mdc` files (except HAND_WRITTEN) with no Claude source.
 */
export function run(argv = process.argv.slice(2)) {
  const gated = argGate(argv, { tool: "tools/gen/gen-cursor-rules.mjs" });
  if (gated !== null) return gated;
  const check = argv.includes("--check");
  const outs = plannedOutputs();
  let code = 0;

  const outDir = path.join(ROOT, OUT_DIR);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  const expected = new Set(outs.map((o) => path.basename(o.rel)));
  for (const ent of fs.readdirSync(outDir)) {
    if (!ent.endsWith(".mdc") || HAND_WRITTEN.has(ent)) continue;
    if (!expected.has(ent)) {
      const msg = `${OUT_DIR}/${ent}: orphan .mdc with no ${SRC_DIR}/${ent.replace(/\.mdc$/, ".md")} — delete it or add the source`;
      if (check) {
        process.stdout.write(`${msg}\n`);
        code = 1;
      } else {
        fs.unlinkSync(path.join(outDir, ent));
        process.stdout.write(`${OUT_DIR}/${ent}: removed orphan\n`);
      }
    }
  }

  for (const { name, rel, content } of outs) {
    if (HAND_WRITTEN.has(`${name}.mdc`)) {
      process.stderr.write(`gen-cursor-rules: refusing to overwrite hand-written ${rel}\n`);
      return 2;
    }
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
    const bytes = Buffer.byteLength(content, "utf8");
    if (check) {
      if (current === content) {
        process.stdout.write(`${rel}: up to date (${bytes} bytes)\n`);
      } else {
        process.stdout.write(`${rel}: STALE — regenerate with \`node tools/gen/gen-cursor-rules.mjs\`\n${firstDiff(current || "", content)}\n`);
        code = 1;
      }
      continue;
    }
    if (current === content) {
      process.stdout.write(`${rel}: unchanged (${bytes} bytes)\n`);
    } else {
      fs.writeFileSync(abs, content);
      process.stdout.write(`${rel}: written (${bytes} bytes)\n`);
    }
  }
  return code;
}

if (isMain(import.meta.url)) process.exit(run());
