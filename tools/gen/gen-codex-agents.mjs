#!/usr/bin/env node
/**
 * gen-codex-agents.mjs — emit `.codex/agents/<name>.toml` from `.claude/agents/<name>.md`.
 * @doc Emit Codex `.codex/agents/*.toml` from `.claude/agents` (body → developer_instructions, tier → effort); `--check`.
 * @skill agent-config
 *
 * `.claude/agents/<name>.md` is the one persona source. Codex reads project
 * custom agents as standalone TOML files under `.codex/agents/`, each with the
 * required `name`, `description` and `developer_instructions`, plus optional
 * `model_reasoning_effort` (https://learn.chatgpt.com/docs/agent-configuration/subagents,
 * the target of https://developers.openai.com/codex/subagents, read 2026-10-26).
 * Codex has no per-agent read-only sandbox (same page: instructions "don't
 * create a separate read-only sandbox"), so a `readonly: true` agent gets the
 * read-only rule as the first line of its instructions.
 *
 * Mapping: `name`, `description` copied; the Claude `model:` TIER becomes the
 * effort (haiku → low, sonnet → medium, opus → high; inherit → omitted, so the
 * parent's applies); no `model` key (Claude model ids mean nothing to Codex).
 *
 *   node tools/gen/gen-codex-agents.mjs            # write every twin
 *   node tools/gen/gen-codex-agents.mjs --check    # exit 1 on any drift
 */
import fs from "node:fs";
import path from "node:path";
import { argGate, firstDiff, isMain, ROOT } from "./gen-lib.mjs";

export const SRC_DIR = ".claude/agents";
export const OUT_DIR = ".codex/agents";
export const EFFORT = { haiku: "low", sonnet: "medium", opus: "high" };

/**
 * Flat `key: scalar` frontmatter, the only shape agent files use (the real-YAML
 * check is tests/unit/skill-progressive.test.mjs). No `yaml` import on purpose:
 * deploy.mjs regenerates on a throwaway copy with no node_modules.
 */
export function parseFrontmatter(src) {
  const fm = {};
  let last = null;
  for (const raw of String(src).split("\n")) {
    const kv = raw.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (kv) {
      const v = kv[2].trim();
      fm[kv[1]] = v.startsWith('"') ? JSON.parse(v)
        : v.startsWith("'") ? v.slice(1, -1).replace(/''/g, "'")
        : v === "true" ? true : v === "false" ? false : v;
      last = kv[1];
    } else if (last && /^\s+\S/.test(raw) && typeof fm[last] === "string") {
      fm[last] += " " + raw.trim(); // folded plain-scalar continuation
    }
  }
  return fm;
}

export function splitAgent(text) {
  const m = String(text).match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) throw new Error("missing YAML frontmatter");
  return { fm: parseFrontmatter(m[1]), body: text.slice(m[0].length) };
}

/** TOML basic string (JSON escapes are a subset TOML accepts for these inputs). */
const tomlString = (s) => JSON.stringify(String(s));

/** Multi-line TOML string: literal ''' when possible (no escapes), else basic """ with escapes. */
export function tomlMultiline(s) {
  const text = String(s).replace(/\s+$/, "") + "\n";
  if (!text.includes("'''")) return `'''\n${text}'''`;
  const esc = text.replace(/\\/g, "\\\\").replace(/"""/g, '""\\"');
  return `"""\n${esc}"""`;
}

export function codexPreamble(fm) {
  const lines = [];
  if (fm.readonly === true) {
    lines.push("READ-ONLY ROLE: never edit, write, move or delete a file, and never commit or push. Codex gives a custom agent no read-only sandbox, so this line is the guard.");
  }
  if (fm.isolation === "worktree") {
    lines.push("Claude Code runs this role in its own git worktree; under Codex, stay inside the OWNED paths the parent names and commit only on the branch it names.");
  }
  lines.push("Tool names below are Claude Code's (Read, Grep, Bash, SendMessage, mcp__<server>__<tool>): use your nearest Codex equivalent; a tool you do not have is UNREAD in your report, never a workaround. Your final message is the hand-back to the parent.");
  return lines.join("\n");
}

export function renderToml(name, srcText) {
  const { fm, body } = splitAgent(srcText);
  if (fm.name !== name) throw new Error(`${SRC_DIR}/${name}.md: frontmatter name "${fm.name}" must match the filename`);
  if (!fm.description) throw new Error(`${SRC_DIR}/${name}.md: description is required`);
  const out = [
    `# generated by tools/gen/gen-codex-agents.mjs — edit ${SRC_DIR}/${name}.md, then \`npm run gen\``,
    `name = ${tomlString(fm.name)}`,
    `description = ${tomlString(String(fm.description).replace(/\s+/g, " ").trim())}`,
  ];
  const effort = EFFORT[String(fm.model || "").trim()];
  if (effort) out.push(`model_reasoning_effort = ${tomlString(effort)}`);
  const instructions = codexPreamble(fm) + "\n\n" + body.replace(/^\n+/, "");
  out.push(`developer_instructions = ${tomlMultiline(instructions)}`);
  return out.join("\n") + "\n";
}

export function listAgentSources() {
  return fs.readdirSync(path.join(ROOT, SRC_DIR))
    .filter((n) => n.endsWith(".md") && n !== "README.md")
    .map((n) => n.replace(/\.md$/, ""))
    .sort();
}

/** @returns {{ name: string, rel: string, content: string }[]} */
export function plannedOutputs() {
  return listAgentSources().map((name) => {
    const src = fs.readFileSync(path.join(ROOT, SRC_DIR, `${name}.md`), "utf8");
    return { name, rel: `${OUT_DIR}/${name}.toml`, content: renderToml(name, src) };
  });
}

/** Write or check every twin; removes (or, with --check, flags) an orphan .toml. Exit: 0 clean, 1 drift, 2 bad argv. */
export function run(argv = process.argv.slice(2)) {
  const gated = argGate(argv, { tool: "tools/gen/gen-codex-agents.mjs" });
  if (gated !== null) return gated;
  const check = argv.includes("--check");
  const outs = plannedOutputs();
  const outDir = path.join(ROOT, OUT_DIR);
  if (!fs.existsSync(outDir)) {
    if (check) { process.stdout.write(`${OUT_DIR}/: missing — run \`node tools/gen/gen-codex-agents.mjs\`\n`); return 1; }
    fs.mkdirSync(outDir, { recursive: true });
  }
  let code = 0;
  const expected = new Set(outs.map((o) => path.basename(o.rel)));
  for (const ent of fs.readdirSync(outDir)) {
    if (!ent.endsWith(".toml") || expected.has(ent)) continue;
    if (check) {
      process.stdout.write(`${OUT_DIR}/${ent}: orphan with no ${SRC_DIR}/${ent.replace(/\.toml$/, ".md")} — regenerate\n`);
      code = 1;
    } else {
      fs.unlinkSync(path.join(outDir, ent));
      process.stdout.write(`${OUT_DIR}/${ent}: removed orphan\n`);
    }
  }
  for (const { rel, content } of outs) {
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
    const bytes = Buffer.byteLength(content, "utf8");
    if (check) {
      if (current === content) process.stdout.write(`${rel}: up to date (${bytes} bytes)\n`);
      else {
        process.stdout.write(`${rel}: STALE — regenerate with \`node tools/gen/gen-codex-agents.mjs\`\n${firstDiff(current || "", content)}\n`);
        code = 1;
      }
    } else if (current === content) {
      process.stdout.write(`${rel}: unchanged (${bytes} bytes)\n`);
    } else {
      fs.writeFileSync(abs, content);
      process.stdout.write(`${rel}: written (${bytes} bytes)\n`);
    }
  }
  return code;
}

if (isMain(import.meta.url)) process.exit(run());
