#!/usr/bin/env node
/**
 * gen-flags-table.mjs — DevFlags registry block in docs/DEBUG-HOOKS.md.
 * @doc Regenerates the DevFlags table in `docs/DEBUG-HOOKS.md` from `js/core/dev-flags.js`; `--check`.
 * @skill check-changes
 *
 *   node tools/gen/gen-flags-table.mjs            # write
 *   node tools/gen/gen-flags-table.mjs --check    # exit 1 when committed ≠ generated
 */
import vm from "node:vm";
import { emit, isMain, readRepo, replaceBlock } from "./gen-lib.mjs";

export const TARGET = "docs/DEBUG-HOOKS.md";
export const SOURCE = "js/core/dev-flags.js";

export function collectFlags() {
  const src = readRepo(SOURCE);
  const ctx = { window: {} };
  vm.runInContext(src + "\n;globalThis.DevFlags = window.DevFlags;", vm.createContext(ctx));
  const DF = ctx.window.DevFlags;
  if (!DF || !DF.REGISTRY) throw new Error(`${SOURCE}: DevFlags.REGISTRY missing`);
  return DF.names().map((name) => {
    const d = DF.REGISTRY[name];
    return {
      name,
      param: d.param || name,
      storage: d.storage ? `apex26.${d.storage}` : "—",
      kind: d.kind || "bool",
      legacyQueryOne: !!d.legacyQueryOne,
      legacyStorageOne: !!d.legacyStorageOne,
      noHash: !!d.noHash,
    };
  });
}

export function renderBlock() {
  const rows = collectFlags();
  const out = [
    "### Dev URL flags (`DevFlags` / `__apex.flags()`)",
    "",
    "_Generated by `node tools/gen/gen-flags-table.mjs` from `REGISTRY` in `" + SOURCE + "` (" + rows.length + " flags). Query, then hash, then localStorage unless noHash. Bool: 1/on/true/yes on, 0/off/false/no off; legacy rows only accept =1/0 in the URL or storage where noted._",
    "",
    "| Flag | Query param | Storage key | Kind | Legacy `=1` query | Legacy storage `1`/`0` | Skips hash |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const r of rows) {
    out.push(
      `| \`${r.name}\` | \`${r.param}\` | \`${r.storage}\` | ${r.kind} | ${r.legacyQueryOne ? "yes" : "—"} | ${r.legacyStorageOne ? "yes" : "—"} | ${r.noHash ? "yes" : "—"} |`,
    );
  }
  out.push("");
  return out.join("\n");
}

export function render(existing) {
  return replaceBlock(existing, "flags-table", renderBlock());
}

if (isMain(import.meta.url)) {
  try {
    process.exitCode = emit(TARGET, render(readRepo(TARGET)));
  } catch (e) {
    process.stderr.write(String(e.message || e) + "\n");
    process.exitCode = 2;
  }
}
