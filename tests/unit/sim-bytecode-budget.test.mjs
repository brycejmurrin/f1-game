/* sim-bytecode-budget.test.mjs — the physics step's functions stay well under TurboFan's size cap.
 *
 * V8 never optimizes a function whose bytecode exceeds --max-optimized-bytecode-size (61,440 B in
 * V8 12.x, Node 22 / Chrome). Past that cliff the WHOLE race runs the step at the baseline tier:
 * measured +19-26 % per step in game-vm for updateCar's deopted steps (docs/notes/PERF-HUNT-2-2026-10-13.md
 * S1/S11). updateCar was 43,086 B — 70 % of the cap — with no guard, and the ratchet lets game.js absorb
 * +40 lines per commit. This pins every function of the fixed-step loop under 48 KB (78 % of the cap),
 * so the cliff is seen in review, not in a phone's frame time.
 *
 * Measured, not estimated: a child `node --no-lazy --print-bytecode` COMPILES js/game.js (vm.Script,
 * never runs it) and every function's "Bytecode length" is read off the listing. ~0.5 s, no browser.
 * Grow a function past the budget → split it (pure extraction, same float ops in the same order), do
 * not raise the budget. Run: node --test tests/unit/sim-bytecode-budget.test.mjs
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { GAME_PATH as GAME } from "../helpers/game-source.mjs";

const TURBOFAN_CAP = 61440;            // V8 --max-optimized-bytecode-size default
const BUDGET = 48 * 1024;              // per function: headroom for the +40-line ratchet steps
// The fixed-step loop: update() → updateCar() per car → its parts, in call order. Every function listed must
// exist (a rename or a split must update this list, so the guard cannot silently stop covering the step).
const SIM_HOT = ["update", "updateCar", "updateCarBrakePlan", "updateCarLongitudinal", "updateCarLateral", "updateCarBicycle", "updateCarAdvance"];

let _sizes = null;
function bytecodeSizes() {
  if (_sizes) return _sizes;
  const r = spawnSync(process.execPath, ["--no-lazy", "--print-bytecode", "-e",
    "new (require('vm').Script)(require('fs').readFileSync(process.argv[1], 'utf8'))", GAME],
  { encoding: "utf8", maxBuffer: 1 << 28 });
  const sizes = new Map();
  let name = null;
  for (const line of (r.stdout || "").split("\n")) {
    const m = /^\[generated bytecode for function: (\S+)/.exec(line);
    if (m) { name = m[1]; continue; }
    const b = /^Bytecode length: (\d+)/.exec(line);
    if (b && name) { sizes.set(name, Math.max(sizes.get(name) || 0, +b[1])); name = null; }
  }
  return (_sizes = sizes);
}

test("every function of the physics step compiles under the bytecode budget (TurboFan cap 61,440 B)", (t) => {
  const sizes = bytecodeSizes();
  if (!sizes.size) { t.skip("this node build prints no bytecode listing"); return; }
  for (const fn of SIM_HOT) {
    assert.ok(sizes.has(fn), `${fn} not found in js/game.js — update SIM_HOT after a rename or split`);
    const n = sizes.get(fn);
    assert.ok(n < BUDGET, `${fn} is ${n} B of bytecode (budget ${BUDGET}, TurboFan never optimizes past ${TURBOFAN_CAP}): split it, do not raise the budget`);
  }
});

test("control: the listing parser reads a real size (a 0-length parse would pass everything)", (t) => {
  const sizes = bytecodeSizes();
  if (!sizes.size) { t.skip("this node build prints no bytecode listing"); return; }
  assert.ok(sizes.get("updateCar") > 1000, "updateCar's size was not parsed");
});
