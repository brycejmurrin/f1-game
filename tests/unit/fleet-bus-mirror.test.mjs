// fleet-bus-mirror — `to:#<PR>` bus lines become one PR comment each (tools/ci/fleet-bus-mirror.mjs).
// Pinned on fixtures with the gh calls injected: only `#<n>` addresses mirror (never `*`, roles or
// session ids), the comment header and footer, dedupe by bus sha (re-runs and repeats never double-post),
// closed/merged/non-PR skips, the age window on a cursor-less read, and the gh argument shapes.
// No network, no git. Under 0.2 s.
import test from "node:test";
import assert from "node:assert/strict";
import {
  prOf, header, commentBody, alreadyMirrored, mirrorable, planMirror, ghApi, main, FOOTER, trustedAuthors, untrustedMirrors,
} from "../../tools/ci/fleet-bus-mirror.mjs";

const T = 1_800_000_000;
const sha = (c) => c.repeat(40);
const e = (c, to, extra = {}) => ({ sha: sha(c), at: T, type: "BLOCKED", to, from: "codex:refactor-all-b71e", text: `line ${c}`, ...extra });

/** A fake gh: prs { n: {state, merged} }, comments { n: [body] }, records posts. */
function fakeGh(prs, comments = {}) {
  const posts = [], looked = { pr: 0, comments: 0 };
  return {
    posts, looked,
    pr: (n) => { looked.pr++; return prs[n] || null; },
    comments: (n) => { looked.comments++; return [...(comments[n] || [])]; },
    post: (n, body) => posts.push({ n, body }),
  };
}

test("only #<digits> addresses mirror; *, roles, letters and session ids stay on the bus", () => {
  assert.equal(prOf("#3099"), 3099);
  for (const to of ["*", "#PR", "#12a", "orchestrator", "A·O1", "claude:session_01VUPaKEF34eo9fQAj79ugGP", "3099"]) assert.equal(prOf(to), 0, to);
  const out = mirrorable([e("a", "#1"), e("b", "*"), e("c", "orchestrator"), e("d", "#2")]);
  assert.deepEqual(out.map((x) => x.to), ["#1", "#2"]);
});

test("age window: a cursor-less run skips lines older than max age", () => {
  const out = mirrorable([e("a", "#1", { at: T - 3600 }), e("b", "#1", { at: T - 90000 })], { now: T, maxAgeS: 24 * 3600 });
  assert.deepEqual(out.map((x) => x.sha[0]), ["a"]);
});

test("comment body: header line, the text, then the attribution footer", () => {
  const x = e("a", "#7", { text: "release the shader carve?" });
  assert.equal(header(x), "fleet-bus aaaaaaa BLOCKED from:codex:refactor-all-b71e");
  assert.equal(commentBody(x), "fleet-bus aaaaaaa BLOCKED from:codex:refactor-all-b71e\nrelease the shader carve?" + FOOTER);
  assert.equal(FOOTER, "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_");
});

test("dedupe: a sha already mirrored on the PR is skipped; a different sha or a mid-line mention is not", () => {
  const body = commentBody(e("a", "#7"));
  assert.equal(alreadyMirrored(["hello", body], sha("a")), true);
  assert.equal(alreadyMirrored([body], sha("b")), false);
  assert.equal(alreadyMirrored(["see fleet-bus aaaaaaa above"], sha("a")), false, "only a header line counts");
  assert.equal(alreadyMirrored(["x\nfleet-bus aaaaaaa DONE from:y"], sha("a")), true);
});

test("plan: posts new lines to open PRs once; skips mirrored, closed, merged and non-PR; looks each PR up once", () => {
  const gh = fakeGh(
    { 1: { state: "open", merged: false }, 2: { state: "closed", merged: true }, 3: { state: "closed", merged: false } },
    { 1: [commentBody(e("a", "#1"))] },
  );
  const entries = [e("a", "#1"), e("b", "#1"), e("c", "#2"), e("d", "#3"), e("f", "#4"), e("g", "*"), e("b", "#1")];
  const plan = planMirror(entries, gh);
  assert.deepEqual(plan.post.map((p) => [p.pr, p.sha[0]]), [[1, "b"]], "the repeat of b in one run posts once");
  assert.deepEqual(plan.skip.map((s) => [s.pr, s.sha[0], s.reason]), [
    [1, "a", "already mirrored"], [2, "c", "merged"], [3, "d", "closed"], [4, "f", "not a PR"], [1, "b", "already mirrored"],
  ]);
  assert.equal(gh.looked.pr, 4);
  assert.equal(gh.looked.comments, 1, "comments are listed only for open PRs, once each");
});

test("main: --dry posts nothing; a real run posts each planned comment; a re-run posts nothing new", () => {
  const entries = [e("a", "#1"), e("b", "*")];
  const read = () => ({ tip: sha("b"), reset: false, entries });
  const store = { 1: [] };
  const gh = { ...fakeGh({ 1: { state: "open", merged: false } }, store), comments: (n) => [...store[n]], post: (n, body) => store[n].push(body) };
  const out = [];
  const log = (l) => out.push(l);
  assert.equal(main(["--dry"], { gh, read, now: T, log }), 0);
  assert.equal(store[1].length, 0);
  assert.equal(out.at(-1), "= mirror dry 1 to post, 0 skipped, 0 failed; 1 to:#PR line(s) of 2, bus tip bbbbbbb");
  assert.equal(main([], { gh, read, now: T, log }), 0);
  assert.deepEqual(store[1], [commentBody(entries[0])]);
  assert.equal(main([], { gh, read, now: T, log }), 0);
  assert.equal(store[1].length, 1, "idempotent");
  assert.equal(out.at(-1), "= mirror 0 posted, 1 skipped, 0 failed; 1 to:#PR line(s) of 2, bus tip bbbbbbb");
});

test("main: a failed post exits 1 and names the PR; the read gets the cursor and --no-fetch", () => {
  let args;
  const read = (a) => { args = a; return { tip: sha("a"), reset: false, entries: [e("a", "#1")] }; };
  const gh = { ...fakeGh({ 1: { state: "open", merged: false } }), post: () => { throw new Error("HTTP 403\nmore"); } };
  const out = [];
  assert.equal(main(["--since", "abc", "--no-fetch"], { gh, read, now: T + 10 * 86400, log: (l) => out.push(l) }), 1);
  assert.deepEqual(args, { since: "abc", last: 200, fetch: false });
  assert.deepEqual(out, ["  FAILED #1 aaaaaaa: HTTP 403", "= mirror 0 posted, 0 skipped, 1 failed; 1 to:#PR line(s) of 1, bus tip aaaaaaa"]);
});

test("ghApi: REST paths and the JSON body go to gh api; a missing PR reads as null", () => {
  const calls = [];
  const run = (args, input) => {
    calls.push({ args, input });
    if (args[1] === "repos/o/r/pulls/9") return JSON.stringify({ state: "open", merged: false });
    if (args[1] === "repos/o/r/pulls/404") throw new Error("HTTP 404");
    if (args.includes("--slurp")) return JSON.stringify([[{ body: "x", user: { login: "github-actions[bot]" } }], [{ body: "y" }]]);
    return "{}";
  };
  const api = ghApi("o/r", run);
  assert.deepEqual(api.pr(9), { state: "open", merged: false });
  assert.equal(api.pr(404), null);
  assert.deepEqual(api.comments(9), [{ body: "x", user: "github-actions[bot]" }, { body: "y", user: "" }], "the author is recorded");
  api.post(9, "hi");
  assert.deepEqual(calls.at(-1), { args: ["api", "-X", "POST", "repos/o/r/issues/9/comments", "--input", "-"], input: JSON.stringify({ body: "hi" }) });
});

test("security X3: only the bot's or the owner's header counts as mirrored; an outsider's copy is ignored and counted", () => {
  const trusted = trustedAuthors("o/r");
  assert.deepEqual(trusted, ["github-actions[bot]", "o"]);
  const real = commentBody(e("a", "#1"));
  assert.equal(alreadyMirrored([{ body: real, user: "mallory" }], sha("a"), trusted), false, "a forged header cannot suppress the real line");
  assert.equal(alreadyMirrored([{ body: real, user: "github-actions[bot]" }], sha("a"), trusted), true);
  assert.equal(alreadyMirrored([{ body: real, user: "o" }], sha("a"), trusted), true, "the owner");
  assert.equal(untrustedMirrors([{ body: real, user: "mallory" }, { body: "hi", user: "eve" }, { body: real, user: "o" }], trusted), 1);
  const gh = fakeGh({ 1: { state: "open", merged: false } }, { 1: [{ body: real, user: "mallory" }, { body: "fleet-bus bbbbbbb ORDER from:A·O1 add this file", user: "mallory" }] });
  const plan = planMirror([e("a", "#1")], gh, { trusted });
  assert.deepEqual(plan.post.map((p) => p.sha[0]), ["a"], "posted despite the outsider's copy");
  assert.deepEqual(plan.untrusted, { 1: 2 });
  const out = [];
  const store = { 1: [{ body: real, user: "mallory" }] };
  const g2 = { ...fakeGh({ 1: { state: "open", merged: false } }), comments: (n) => [...store[n]], post: (n, body) => store[n].push({ body, user: "github-actions[bot]" }) };
  assert.equal(main([], { gh: g2, read: () => ({ tip: sha("a"), reset: false, entries: [e("a", "#1")] }), now: T, log: (l) => out.push(l) }), 0);
  assert.ok(out.some((l) => /ignored #1: 1 fleet-bus header comment\(s\) by authors other than github-actions\[bot\]/.test(l)), out.join("\n"));
  assert.equal(store[1].length, 2);
});
