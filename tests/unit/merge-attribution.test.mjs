const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const HEAD = "b".repeat(40);
const SHA = "c".repeat(40);

test("mergeTrailers: Merged-by and Gate lines under the PR title, identity from whoAmI", () => {
  const m = mergeTrailers({ by: "claude:session_01ABC", fleet: "A", role: "orchestrator", head: HEAD, title: "feat: x" });
  assert.equal(m, `feat: x\n\nMerged-by: claude:session_01ABC (A/orchestrator)\nGate: merge-gate ${HEAD.slice(0, 12)}`);
  assert.deepEqual(parseAttribution(m), { by: "claude:session_01ABC", fleet: "A", role: "orchestrator", gate: HEAD.slice(0, 12) });
});

test("mergeTrailers: no identity falls back to unknown:unidentified, missing fleet/role to ?", () => {
  const m = mergeTrailers({ by: null, head: HEAD });
  assert.ok(m.startsWith(`Merged-by: ${UNKNOWN_IDENTITY} (?/?)\n`));
  assert.equal(parseAttribution(m).by, UNKNOWN_IDENTITY, "an unidentified merge is still ATTRIBUTED as a gate merge");
});

test("parseAttribution: only a Merged-by line counts; prose mentioning it does not", () => {
  assert.equal(parseAttribution("Merge pull request #1 from o/b\n\nfix a thing"), null);
  assert.equal(parseAttribution("the Merged-by trailer is how..."), null);
  assert.equal(parseAttribution("t\n\nMerged-by: cursor:bc-abc123456 (D/worker)").role, "worker");
});

test("prOfSubject: merge-commit and (#n) forms", () => {
  assert.equal(prOfSubject("Merge pull request #3548 from brycejmurrin/cursor/x"), 3548);
  assert.equal(prOfSubject("feat: thing (#12)"), 12);
  assert.equal(prOfSubject("Merge branch 'x'"), 0);
});

test("classify: fixture commit messages", () => {
  const ok = classify({ sha: SHA, subject: "Merge pull request #7 from o/b", body: "title\n\nMerged-by: claude:s (A/orchestrator)\nGate: merge-gate abc", author: "brycejmurrin" });
  const bad = classify({ sha: SHA, subject: "Merge pull request #8 from o/b", body: "title only", author: "brycejmurrin" });
  assert.equal(ok.state, "ATTRIBUTED");
  assert.equal(ok.pr, 7);
  assert.equal(bad.state, "UNATTRIBUTED");
  assert.equal(bad.pr, 8);
});

test("mergeCall + fleetOf: commit_title is GitHub's own, the message carries the trailers", () => {
  assert.equal(fleetOf("intro\n```fleet\nworker: claude:s\nfleet: A\norchestrator: A\n```"), "A");
  assert.equal(fleetOf("no block"), "");
  const c = mergeCall({ pull: { head: { label: "o:cursor/x", ref: "cursor/x" }, title: "T", body: "```fleet\nfleet: D\n```" }, pr: 9, head: HEAD, by: "claude:s", role: "merge-holder" });
  assert.equal(c.commit_title, "Merge pull request #9 from o/cursor/x");
  assert.equal(c.expectedHeadSha, HEAD);
  assert.ok(/Merged-by: claude:s \(D\/merge-holder\)\nGate: merge-gate b{12}$/.test(c.commit_message));
});

const fakeGh = (existing = {}) => {
  const posted = [];
  return { posted, comments: (n) => [...(existing[n] || []), ...posted.filter((p) => p.n === n).map((p) => p.body)], post: (n, body) => posted.push({ n, body }) };
};

test("flag: one comment + one bus line per UNATTRIBUTED merge; ATTRIBUTED are left alone", () => {
  const rows = [classify({ sha: SHA, subject: "Merge pull request #8 from o/b", body: "", author: "u" }), classify({ sha: "d".repeat(40), subject: "Merge pull request #9 from o/b", body: "Merged-by: claude:s (A/o)", author: "u" })];
  const gh = fakeGh(), sent = [];
  const out = flag(rows, { gh, sendBus: (t) => (sent.push(t), true) });
  assert.deepEqual(out.map((o) => [o.pr, o.comment, o.bus]), [[8, "posted", "posted"]]);
  assert.equal(gh.posted.length, 1);
  assert.ok(/merged without attribution: Bryce UI merge, or an agent\? reply here if it was you/.test(gh.posted[0].body));
  assert.ok(/Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)/.test(gh.posted[0].body));
  assert.ok(gh.posted[0].body.includes(marker(SHA)));
  assert.ok(/^merge-attribution: UNATTRIBUTED merge cccccccc #8/.test(sent[0]));
});

test("flag: idempotent — a second pass posts neither the comment nor the bus line", () => {
  const rows = [classify({ sha: SHA, subject: "Merge pull request #8 from o/b", body: "", author: "u" })];
  const gh = fakeGh(), sent = [], busEntries = [];
  flag(rows, { gh, sendBus: (t) => (sent.push(t), true), busEntries });
  const again = flag(rows, { gh, sendBus: (t) => (sent.push(t), true), busEntries });
  assert.deepEqual(again.map((o) => [o.comment, o.bus]), [["exists", "exists"]]);
  assert.equal(gh.posted.length, 1);
  assert.equal(sent.length, 1);
  assert.equal(busHas([{ text: busText(rows[0]) }], SHA), true);
  assert.ok(commentBody(rows[0]).includes(marker(SHA)));
});

test("flag: --dry-run posts nothing; --no-bus / --no-comment each skip their channel", () => {
  const rows = [classify({ sha: SHA, subject: "Merge pull request #8 from o/b", body: "", author: "u" })];
  const gh = fakeGh(), sent = [];
  const dry = flag(rows, { gh, sendBus: (t) => (sent.push(t), true), dry: true });
  assert.deepEqual(dry.map((o) => [o.comment, o.bus]), [["dry-run", "dry-run"]]);
  assert.equal(gh.posted.length + sent.length, 0);
  const noBus = flag(rows, { gh, sendBus: (t) => (sent.push(t), true), bus: false });
  assert.deepEqual(noBus.map((o) => [o.comment, o.bus]), [["posted", "skipped"]]);
  assert.equal(sent.length, 0);
  const noComment = flag(rows, { gh: fakeGh(), sendBus: () => true, comment: false });
  assert.deepEqual(noComment.map((o) => [o.comment, o.bus]), [["skipped", "posted"]]);
});

test("flag: a merge with no PR number gets a bus line but no comment; a comment error is reported, not thrown", () => {
  const rows = [classify({ sha: SHA, subject: "Merge branch 'x' into y", body: "", author: "u" })];
  assert.equal(flag(rows, { gh: fakeGh(), sendBus: () => true })[0].comment, "none");
  const boom = { comments: () => { throw new Error("HTTP 403"); }, post() {} };
  const r = flag([classify({ sha: SHA, subject: "Merge pull request #8 from o/b", body: "", author: "u" })], { gh: boom, sendBus: () => true });
  assert.ok(/^error: HTTP 403/.test(r[0].comment));
});

// ---- real git: listMerges over a throw-away repo, then main --dry-run ---------------

function fixtureRepo() {
  const dir = fs.mkdtempSync(path.join(fs.mkdirSync(path.join(ROOT, "artifacts", "tmp"), { recursive: true }) || path.join(ROOT, "artifacts", "tmp"), "merge-attr-"));
  const g = (...a) => spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...a], { cwd: dir, encoding: "utf8" });
  g("init", "-q", "-b", "main");
  fs.writeFileSync(path.join(dir, "f"), "0\n"); g("add", "."); g("commit", "-qm", "root");
  const merge = (n, msg) => {
    g("checkout", "-qb", `b${n}`); fs.writeFileSync(path.join(dir, `f${n}`), `${n}\n`); g("add", "."); g("commit", "-qm", `work ${n}`);
    g("checkout", "-q", "main"); g("merge", "--no-ff", "-q", "-m", `Merge pull request #${n} from o/b${n}`, "-m", msg, `b${n}`);
  };
  merge(1, "title one\n\nMerged-by: claude:session_X (A/orchestrator)\nGate: merge-gate aaaaaaaaaaaa");
  merge(2, "title two");
  return dir;
}

test("listMerges + main --dry-run over real merge commits: one ATTRIBUTED, one UNATTRIBUTED, nothing posted", () => {
  const dir = fixtureRepo();
  try {
    const l = listMerges({ range: "HEAD~2..HEAD", cwd: dir });
    assert.deepEqual(l.merges.map((m) => prOfSubject(m.subject)), [1, 2]);
    const lines = [];
    const code = main(["--range", "HEAD~2..HEAD", "--dry-run", "--no-bus"], { root: dir, log: (s) => lines.push(s), read: () => ({ entries: [] }) });
    assert.equal(code, 0);
    assert.ok(/^ATTRIBUTED\s+\S+ #1 .*claude:session_X \(A\/orchestrator\)/.test(lines[0]));
    assert.ok(/^UNATTRIBUTED\s+\S+ #2 /.test(lines[1]));
    assert.ok(/^= merge-attribution 2 merges, 1 attributed, 1 unattributed, 0 flagged \(dry run: nothing posted\)/.test(lines.at(-1)));
    assert.ok(!fs.existsSync(path.join(dir, "artifacts", "merge-attribution", "cursor")), "a dry run or an explicit range never moves the cursor");
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});

test("main: a bad range is exit 1 with an error line", () => {
  const lines = [];
  assert.equal(main(["--range", "nope..nope", "--dry-run"], { root: ROOT, log: (s) => lines.push(s), read: () => ({ entries: [] }) }), 1);
  assert.ok(/= merge-attribution error/.test(lines[0]));
});

// --digest (2026-10-26): ONE INFO line per window instead of one HANDOFF per merge; idempotent on the newest
// unattributed sha; silent when every merge carries the trailer.
test("digest: one INFO body for the window, a valid bus line, idem on the newest unattributed sha", () => {
  const A = "a".repeat(40), B = "b".repeat(40), C = "c".repeat(40);
  const rows = [
    { sha: A, pr: 10, state: "UNATTRIBUTED" },
    { sha: B, pr: 11, state: "ATTRIBUTED" },
    { sha: C, pr: null, state: "UNATTRIBUTED" },
  ];
  const text = digestText(rows, "x..y");
  // A PR number, else the short sha; the attributed #11 is not listed.
  assert.equal(text, "merge-attribution digest: 2 of 3 merges in x..y carry no Merged-by: trailer (presumed Bryce UI merges): " +
    "#10 cccccccc. An agent merge? Merge through merge-gate.mjs so the trailer lands.");
  assert.equal(digestIdem(rows), `merge-attr:${C.slice(0, 12)}`);
  // fleet-bus accepts it as an INFO line from the workflow's identity (formatLine throws on a bad type/body/idem).
  assert.ok(formatLine("INFO", "*", DIGEST_FROM, text, { idem: digestIdem(rows) }).startsWith(`INFO to:* from:${DIGEST_FROM} merge-attribution digest:`));
  assert.equal(digestText([{ sha: B, pr: 11, state: "ATTRIBUTED" }], "x..y"), "");
  const many = Array.from({ length: 25 }, (_, i) => ({ sha: String(i).padStart(40, "0"), pr: 100 + i, state: "UNATTRIBUTED" }));
  assert.ok(digestText(many, "r").endsWith("#119 +5 more. An agent merge? Merge through merge-gate.mjs so the trailer lands."), "capped at 20 PRs");
});

test("main --digest over real merges sends ONE INFO line (no per-merge flags); none unattributed sends nothing", () => {
  const dir = fixtureRepo();
  try {
    const sent = [], lines = [];
    const send = (...a) => { sent.push(a); return { ok: true, sha: "abc1234" }; };
    const gh = { comments: () => { throw new Error("digest must not read PR comments"); }, post: () => { throw new Error("digest must not post"); } };
    assert.equal(main(["--range", "HEAD~2..HEAD", "--digest"], { root: dir, log: (s) => lines.push(s), gh, read: () => ({ entries: [] }), send }), 0);
    assert.equal(sent.length, 1);
    const [type, to, from, text, opts] = sent[0];
    assert.deepEqual([type, to, from], ["INFO", "*", DIGEST_FROM]);
    assert.equal(text, "merge-attribution digest: 1 of 2 merges in HEAD~2..HEAD carry no Merged-by: trailer (presumed Bryce UI merges): " +
      "#2. An agent merge? Merge through merge-gate.mjs so the trailer lands.");
    assert.ok(opts.idem.startsWith("merge-attr:"));
    assert.ok(lines.at(-1).startsWith("= merge-attribution digest 2 merges, 1 unattributed: sent"));
    sent.length = 0;
    assert.equal(main(["--range", "HEAD~2..HEAD~1", "--digest"], { root: dir, log: (s) => lines.push(s), gh, read: () => ({ entries: [] }), send }), 0);
    assert.equal(sent.length, 0, "every merge attributed: nothing sent");
    assert.equal(main(["--range", "HEAD~2..HEAD", "--digest", "--dry-run"], { root: dir, log: (s) => lines.push(s), gh, read: () => ({ entries: [] }), send }), 0);
    assert.equal(sent.length, 0, "a dry run sends nothing");
    assert.equal(main(["--range", "HEAD~2..HEAD", "--digest"], { root: dir, log: (s) => lines.push(s), gh, read: () => ({ entries: [] }), send: () => ({ ok: false, reason: "push refused" }) }), 1,
      "a failed send is exit 1, so the job shows it");
    assert.ok(!fs.existsSync(path.join(dir, "artifacts", "merge-attribution", "cursor")));
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});
